#!/usr/bin/env python3
"""Turn raw pose tracks (from extract-poses.html) into StepSync keyframe dances: stepsync/js/video-dances.js.

Usage (from the repo root):  python3 stepsync/tools/make_video_dances.py
Steps: drop glitch frames, fill gaps, median + moving-average smoothing (handles left/right flips),
resample to an exact number of keys per clip so repeats stay in time with the looping music,
and blend the last keys into the first so the loop is seamless.
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'js', 'video-dances.js')
SEGS = ['torso', 'uaL', 'faL', 'uaR', 'faR', 'thL', 'shL', 'thR', 'shR']

DANCES = [
    dict(id='ai-calm', pose_file='calm_dance4.json', title='Calm Dance', subtitle='A slow dance to help you calm down, generated from an EDGE video',
         color='#48bfe3', music='calm', bpm=71.5, repeat=3, phraseBeats=2),
    dict(id='ai-happy', pose_file='happy_dance500.json', title='Happy Dance', subtitle='An upbeat dance to cheer you up, generated from an EDGE video',
         color='#2ecc71', music='happy', bpm=80.5, repeat=2, phraseBeats=2),
]


def wrap(a):
    return (a + 180) % 360 - 180


def unwrap(vals):
    out, prev = [], None
    for v in vals:
        if v is None:
            out.append(None); continue
        if prev is not None:
            v = prev + wrap(v - prev)
        out.append(v); prev = v
    return out


def fill(vals):
    idx = [i for i, v in enumerate(vals) if v is not None]
    if not idx:
        return [0.0] * len(vals)
    out = list(vals)
    for i in range(len(out)):
        if out[i] is None:
            a = max([j for j in idx if j < i], default=None)
            b = min([j for j in idx if j > i], default=None)
            out[i] = out[b] if a is None else out[a] if b is None else out[a] + (out[b] - out[a]) * (i - a) / (b - a)
    return out


def median(vals, k=5):
    h = k // 2
    return [sorted(vals[max(0, i - h):i + h + 1])[len(vals[max(0, i - h):i + h + 1]) // 2] for i in range(len(vals))]


def mean(vals, k=3):
    h = k // 2
    return [sum(vals[max(0, i - h):i + h + 1]) / len(vals[max(0, i - h):i + h + 1]) for i in range(len(vals))]


def build(d):
    raw = json.load(open(os.path.join(HERE, 'poses', d['pose_file'])))
    frames, duration, fps = raw['frames'], raw['duration'], raw['fps']
    heights = sorted(f['poses'][0]['h'] for f in frames if f['poses'])
    med_h = heights[len(heights) // 2]
    good = [f['poses'][0] if f['poses'] and abs(f['poses'][0]['h'] - med_h) / med_h < 0.25 else None for f in frames]
    times = [f['t'] for f in frames]
    tracks = {}
    for s in SEGS:
        vals = [p['seg'][s][0] if p and p['seg'][s][1] >= 0.5 else None for p in good]
        tracks[s] = mean(median(fill(unwrap(vals)), 3))
    n = round(duration * fps)
    keys = []
    for i in range(n):
        t = i * duration / n
        j = min(len(times) - 2, max(0, int(t * fps)))
        f = min(1, max(0, (t - times[j]) / (times[j + 1] - times[j])))
        keys.append([tracks[s][j] + (tracks[s][j + 1] - tracks[s][j]) * f for s in SEGS])
    blend = 4
    for k in range(1, blend + 1):
        w = k / (blend + 1)
        keys[n - blend - 1 + k] = [a + wrap(b - a) * w for a, b in zip(keys[n - blend - 1 + k], keys[0])]
    used = sum(1 for p in good if p)
    print(f"{d['id']}: {used}/{len(frames)} frames used, {n} keys over {duration:.3f}s")
    out = {k: v for k, v in d.items() if k != 'pose_file'}
    out['keyBeats'] = round(duration / n * d['bpm'] / 60, 6)
    out['keys'] = [[round(wrap(a)) for a in key] for key in keys]
    return out


def main():
    dances = [build(d) for d in DANCES]
    body = ',\n'.join(
        '  {\n' + ''.join(f'    {k}: {json.dumps(v)},\n' for k, v in d.items() if k != 'keys')
        + '    keys: [\n' + ''.join(f'      {json.dumps(k)},\n' for k in d['keys']) + '    ],\n  }'
        for d in dances)
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by stepsync/tools/make_video_dances.py from the EDGE videos in videos/ - do not edit by hand.\n'
                 '// Each key = segment angles [' + ', '.join(SEGS) + '], evenly spaced over one loop of the music clip.\n'
                 'export const VIDEO_DANCES = [\n' + body + ',\n];\n')
    print('wrote', os.path.relpath(OUT))


main()
